def area(a, h): 
    '''Принимает основание a и высоту h, возвращает площадь треугольника с основанием a и высотой h
       Пример: Вводные знанение: 2 6. Вывод: 6
       Параметры: a - сторона треугольника, h - высота треугольника'''
    return a * h / 2 

def perimeter(a, b, c): 
    '''Принимает стороны a b c, возвращает периметр треугольника с сторонами a b c
       Пример: Вводные знанение: 3 4 5. Вывод: 12
       Параметры'''
    return a + b + c 
