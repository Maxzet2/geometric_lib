import math


def area(r):
    '''Принимает радиус r, возвращает площадь круга с радиусом r
       Пример: Вводные знанение: 3. Вывод: 28.274333882308138'''
    return math.pi * r * r


def perimeter(r):
    '''Принимает радиус r, возвращает периметр круга с радиусом r
       Пример: Вводные знанение: 3. Вывод: 18.84955592153876'''
    return 2 * math.pi * r

